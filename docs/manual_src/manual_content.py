EQ_DRIFT = ([mrun("Drift rel = "),
             mfrac([mrun("t")], [msub([mrun("t")], [mrun("RIP")])])],
            "把漂移時間除以 RIP 的漂移時間。RIP 自己因此永遠是 1.0，"
            "不同機器之間才比得起來。")

EQ_RI = ([mrun("RI = 100 × ("), msub([mrun("n")], [mrun(" ")]),
          mrun(" + "),
          mfrac([mrun("log t − log "), msub([mrun("t")], [mrun("n")])],
                [mrun("log "), msub([mrun("t")], [mrun("n+1")]),
                 mrun(" − log "), msub([mrun("t")], [mrun("n")])]),
          mrun(")")],
         "保留指數的算法。t 是這顆峰的時間，t(n) 與 t(n+1) 是它前後兩個標準品的時間。"
         "**注意是 log**——時間本身不是等距的，取對數之後才是。")

EQ_R005 = ([mfrac([mrun("突出度")],
                  [mrun("強度 − 基準線")]),
            mrun(" ≧ min_ratio")],
           "規則 R005 的判斷式。分母是「這顆峰高出背景多少」，"
           "分子是「它比左右鄰居高出多少」。比值太小＝那只是一個肩膀，不是獨立的峰。")

EQ_RT = ([msub([mrun("t")], [mrun("step")]),
          mrun(" = (averages + 1) × trigger_repetition")],
         "縱軸每一格代表多少時間。**那個 +1 不能省**——"
         "少了它整條縱軸會短 16.7%，而且畫面上完全看不出異常。")

EQ_WIN = ([mrun("| "), msub([mrun("RI")], [mrun("峰")]),
           mrun(" − "), msub([mrun("RI")], [mrun("資料庫")]),
           mrun(" | ≦ 5")],
          "比對的容許範圍。橫軸那一條同理，只是門檻是 0.05。")



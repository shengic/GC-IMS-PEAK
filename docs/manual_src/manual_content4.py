    a(("h2", "教學 19　五個常見的錯誤解讀"))
    a(("p", "這些都是實際容易發生的誤會。看過一遍可以省下不少麻煩。"))

    a(("h3", "錯誤一：把 GC 欄的名字當成鑑定結果"))
    a(("p", "**看到的**：GC 欄寫著一個化合物名稱。"))
    a(("p", "**誤會**：「找到這個化合物了。」"))
    a(("p", "**實際上**：那只代表**縱軸**對得上。"
            "在近萬筆資料裡，±5 的範圍常常框到幾十個化合物，"
            "顯示的只是其中最接近的一個。"))
    a(("p", "**正確作法**：以 **GC×IMS** 欄為準，並看候選有幾個。"))

    a(("h3", "錯誤二：用峰的數量比較樣品"))
    a(("p", "**看到的**：A 有 45 顆峰，B 有 38 顆。"))
    a(("p", "**誤會**：「A 的成分比較複雜。」"))
    a(("p", "**實際上**：峰數受規則設定影響極大。"
            "同一個檔把 R002 設成 10，馬上就只剩 10 顆。"))
    a(("p", "**正確作法**：比較同一個位置的訊號大小，不要比峰數。"))

    a(("h3", "錯誤三：以為強度就是濃度"))
    a(("p", "**看到的**：某顆峰強度 4,936，是全圖最強。"))
    a(("p", "**誤會**：「這個成分含量最高。」"))
    a(("p", "**實際上**：不同化合物在這台儀器上的靈敏度差很多。"
            "有些含量很低但訊號很強，反之亦然。"))
    a(("p", "**正確作法**：這支程式**不做定量**，不要從強度推濃度。"))

    a(("h3", "錯誤四：忽略 assumed_unverified"))
    a(("p", "**看到的**：工具列角落有一行小字。"))
    a(("p", "**誤會**：「應該不重要吧。」"))
    a(("p", "**實際上**：它代表整批 RI 的來源還有未解的疑問，"
            "而所有比對結果都建立在 RI 上。"))
    a(("p", "**正確作法**：把它和結果一起記錄下來。"))

    a(("h3", "錯誤五：以為三次重複一致就是對的"))
    a(("p", "**看到的**：同一個樣品跑三次，結果都指向同一個化合物。"))
    a(("p", "**誤會**：「三次都一樣，一定沒錯。」"))
    a(("p", "**實際上**：重複測量驗證的是**穩定性**，不是**正確性**。"
            "如果 RI 尺標偏了 300，三次會一致地指向同一個錯誤答案。"))
    a(("p", "**正確作法**：重複一致可以提高信心，"
            "但不能取代對校正來源的確認。"))
